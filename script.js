/* ============================================================
   LANGUAGE TOGGLE
   ============================================================ */
let currentLang = 'es';

function applyLang(l) {
  currentLang = l;
  document.documentElement.lang = l;
  const dict = T[l];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.getAttribute('data-i18n');
    if (dict[k] !== undefined) el.textContent = dict[k];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const k = el.getAttribute('data-i18n-html');
    if (dict[k] !== undefined) el.innerHTML = dict[k];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const k = el.getAttribute('data-i18n-ph');
    if (dict[k] !== undefined) el.placeholder = dict[k];
  });

  // toggle button label
  const tBtn = document.getElementById('langToggle');
  if (tBtn) tBtn.querySelector('.lang-label').textContent = l === 'es' ? 'EN' : 'ES';

  // persist
  try { localStorage.setItem('ennef.lang', l); } catch(e) {}
}

/* ============================================================
   FORM SUBMIT
   ============================================================ */
function submitForm(e) {
  e.preventDefault();
  const btn = e.target.querySelector('.form-submit');
  const labelEl = btn.querySelector('.form-btn-label');
  const originalLabel = labelEl.textContent;
  btn.disabled = true;
  labelEl.textContent = T[currentLang]['form-sending'];

  const data = {
    name:    document.getElementById('f-name').value.trim(),
    email:   document.getElementById('f-email').value.trim(),
    service: document.getElementById('f-service').value.trim(),
    message: document.getElementById('f-msg').value.trim()
  };

  fetch('https://formspree.io/f/xojbqqrz', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'Accept': 'application/json' },
    body: JSON.stringify(data)
  })
  .then(r => {
    if (r.ok) {
      document.getElementById('contactForm').reset();
      document.getElementById('modalOverlay').classList.add('open');
    } else {
      alert(T[currentLang]['err-send']);
    }
  })
  .catch(() => alert(T[currentLang]['err-conn']))
  .finally(() => {
    btn.disabled = false;
    labelEl.textContent = T[currentLang]['form-btn'];
  });
}

